def generate_sitemap_xml(all_pages: dict, base_url: str) -> str:
    """Generate a complete XML sitemap from crawled pages.
    
    Args:
        all_pages: Dict of {norm_url: page_info} from the crawler
        base_url: The base URL of the site
    
    Returns:
        Complete sitemap.xml content as string
    """
    today = datetime.now().strftime("%Y-%m-%d")
    
    urls = []
    for norm_url, page_info in all_pages.items():
        if not page_info.get("parsed"):
            continue
        
        page_url = page_info["parsed"].get("url", norm_url)
        
        # Determine priority based on URL depth
        path = urlparse(page_url).path
        depth = len([p for p in path.split("/") if p])
        
        if depth == 0:  # Homepage
            priority = "1.0"
            changefreq = "daily"
        elif depth == 1:  # Top-level pages
            priority = "0.8"
            changefreq = "weekly"
        elif depth == 2:  # Sub-pages
            priority = "0.6"
            changefreq = "weekly"
        else:  # Deep pages
            priority = "0.4"
            changefreq = "monthly"
        
        urls.append({
            "loc": page_url,
            "lastmod": today,
            "changefreq": changefreq,
            "priority": priority,
        })
    
    # Sort: homepage first, then by priority descending
    urls.sort(key=lambda u: (-float(u["priority"]), u["loc"]))
    
    xml_lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ]
    
    for u in urls:
        xml_lines.append("  <url>")
        xml_lines.append(f"    <loc>{_escape_xml(u['loc'])}</loc>")
        xml_lines.append(f"    <lastmod>{u['lastmod']}</lastmod>")
        xml_lines.append(f"    <changefreq>{u['changefreq']}</changefreq>")
        xml_lines.append(f"    <priority>{u['priority']}</priority>")
        xml_lines.append("  </url>")
    
    xml_lines.append("</urlset>")
    
    return "\n".join(xml_lines)


