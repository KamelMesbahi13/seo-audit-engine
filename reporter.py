def _summarize_category_items(items: list) -> list:
    """Group items by issue concept and produce an executive summary list without raw code dumps."""
    grouped = {}
    sev_rank = {"critical": 4, "high": 3, "medium": 2, "low": 1, "info": 0}

    for item in items:
        f = item.get("finding", {})
        fix = item.get("fix", {})
        issue = f.get("issue", "Unspecified Issue").strip()
        page = item.get("page", "")

        # Clean common prefixes like "[CRITICAL DEFECT]", "[HIGH PRIORITY]", etc.
        clean_issue = re.sub(r"^\[.*?\]\s*", "", issue)
        norm_key = clean_issue.split(" — ")[0].split(" (")[0].strip()

        if norm_key not in grouped:
            fix_summary = ""
            if isinstance(fix, dict):
                fix_summary = fix.get("summary", "")
                if not fix_summary:
                    raw_fix = fix.get("fix", "")
                    if isinstance(raw_fix, str):
                        lines = [l.strip() for l in raw_fix.split("\n") if l.strip() and not l.strip().startswith(("<", "{", "http", "Strict-", "X-", "User-agent", "Sitemap:", "/*", "//"))]
                        fix_summary = " ".join(lines[:2]) if lines else ""
                fix_title = fix.get("title", f"Remediate {norm_key}")
            else:
                fix_title = f"Remediate {norm_key}"

            # Clean any raw html tags
            fix_summary = re.sub(r"<[^>]+>", "", fix_summary).strip()
            # If fix_summary has code artifacts or is too short, provide clean executive instruction
            if '"@context"' in fix_summary or "{" in fix_summary or len(fix_summary) < 20 or fix_summary.startswith("Replace:"):
                norm_lower = norm_key.lower()
                if "h3" in norm_lower or "heading" in norm_lower:
                    fix_summary = "Replace semantic heading tags with standard paragraphs or span elements styled via CSS classes."
                elif "schema" in norm_lower or "structured data" in norm_lower:
                    fix_summary = "Deploy valid Schema.org JSON-LD structured data in document <head> to enable rich search snippets."
                elif "title" in norm_lower:
                    fix_summary = "Ensure title tags are 50-60 characters and contain primary target keywords."
                elif "description" in norm_lower:
                    fix_summary = "Author unique 120-155 character meta descriptions highlighting page value proposition."
                elif "image" in norm_lower or "alt" in norm_lower:
                    fix_summary = "Add descriptive alt attributes and specify width/height dimensions on image elements."
                elif "sitemap" in norm_lower:
                    fix_summary = "Generate and publish an XML sitemap at /sitemap.xml and declare in robots.txt."
                elif "security" in norm_lower or "header" in norm_lower:
                    fix_summary = "Configure modern HTTP security headers (HSTS, CSP, X-Frame-Options) on web server."
                else:
                    fix_summary = f"Implement corrective configuration and structural updates for {norm_key.lower()}."

            if len(fix_summary) > 220:
                fix_summary = fix_summary[:217] + "..."

            detail = f.get("detail", "")
            if not detail:
                detail = clean_issue
            detail = re.sub(r"<[^>]+>", "", detail).strip()
            if "data:image" in detail:
                detail = re.sub(r'data:image/[^;]+;base64,[^\s]+', '[image data]', detail)
            if len(detail) > 220:
                detail = detail[:217] + "..."

            grouped[norm_key] = {
                "issue": norm_key,
                "severity": f.get("severity", "medium").lower(),
                "pages": set(),
                "detail": detail,
                "fix_title": fix_title,
                "fix_summary": fix_summary,
            }

        if page and page != "Site-Wide Infrastructure":
            grouped[norm_key]["pages"].add(page)

        current_sev = grouped[norm_key]["severity"]
        item_sev = f.get("severity", "medium").lower()
        if sev_rank.get(item_sev, 0) > sev_rank.get(current_sev, 0):
            grouped[norm_key]["severity"] = item_sev

    result = []
    for k, v in grouped.items():
        page_count = len(v["pages"])
        if page_count == 0:
            scope_str = "Site-Wide Infrastructure"
        elif page_count == 1:
            p_clean = unquote(urlparse(list(v["pages"])[0]).path or "/")
            scope_str = f"1 Page ({p_clean})"
        else:
            sample = list(v["pages"])[:3]
            sample_paths = [unquote(urlparse(p).path or "/") for p in sample]
            scope_str = f"{page_count} Pages Affected ({', '.join(sample_paths)})"

        result.append({
            "issue": v["issue"],
            "severity": v["severity"],
            "scope": scope_str,
            "problem_summary": v["detail"] or v["issue"],
            "fix_title": v["fix_title"],
            "fix_summary": v["fix_summary"],
        })

    result.sort(key=lambda x: sev_rank.get(x["severity"], 0), reverse=True)
    return result


def _render_category_summary_table(items: list) -> str:
    """Render a clean, concise executive summary table of problems and fixes."""
    summarized = _summarize_category_items(items)
    if not summarized:
        return '<div class="summary-empty-notice">[PASSED] Zero compliance defects identified. All category checks passed.</div>'

    html_out = ['<table class="summary-cat-table">']
    html_out.append('<colgroup><col style="width: 14%;"><col style="width: 43%;"><col style="width: 43%;"></colgroup>')
    html_out.append('<thead><tr>')
    html_out.append('<th style="text-align: center;">Severity</th>')
    html_out.append('<th>Identified Defect &amp; Scope Summary</th>')
    html_out.append('<th>Strategic Fix &amp; Remediation Summary</th>')
    html_out.append('</tr></thead><tbody>')

    for entry in summarized:
        sev = entry["severity"].lower()
        badge_cls = "badge-critical" if sev == "critical" else ("badge-high" if sev == "high" else ("badge-medium" if sev == "medium" else "badge-low"))
        badge_text = sev.upper()

        html_out.append('<tr>')
        html_out.append(f'<td style="text-align: center; vertical-align: top;"><span class="badge {badge_cls}">[{badge_text}]</span></td>')
        html_out.append(f'<td><strong>{_e(entry["issue"])}</strong><br>'
                        f'<span class="summary-scope-tag">{_e(entry["scope"])}</span>'
                        f'<div class="summary-desc-text">{_e(entry["problem_summary"])}</div></td>')
        html_out.append(f'<td><div class="summary-fix-title">{_e(entry["fix_title"])}</div>'
                        f'<div class="summary-fix-text">{_e(entry["fix_summary"])}</div></td>')
        html_out.append('</tr>')

    html_out.append('</tbody></table>')
    return "\n".join(html_out)


