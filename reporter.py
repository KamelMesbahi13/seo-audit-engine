# ---------------------------------------------------------------------------
# PDF Renderer via Playwright
# ---------------------------------------------------------------------------

def render_pdf(html_content: str, output_path: str):
    """Render HTML string to A4 PDF using headless Chromium."""
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        print("ERROR: Playwright not installed. Install with: pip install playwright")
        sys.exit(1)

    playwright_paths = [
        os.path.expanduser("~/.gemini/config/skills/claude-seo/ms-playwright"),
        os.path.expanduser("~/.claude/skills/seo/ms-playwright"),
    ]

    browser_path = None
    for pw_path in playwright_paths:
        if os.path.exists(pw_path):
            for dirpath, dirnames, filenames in os.walk(pw_path):
                for fn in filenames:
                    if fn in ("chrome.exe", "chromium.exe", "chromium"):
                        browser_path = os.path.join(dirpath, fn)
                        break
                if browser_path:
                    break
        if browser_path:
            break

    if os.path.exists(playwright_paths[0]):
        os.environ["PLAYWRIGHT_BROWSERS_PATH"] = playwright_paths[0]

    print(f"  [reporter] Rendering PDF with Playwright...")

    with sync_playwright() as p:
        launch_args = {"headless": True}
        if browser_path:
            launch_args["executable_path"] = browser_path

        browser = p.chromium.launch(**launch_args)
        page = browser.new_page()
        page.set_content(html_content, wait_until="networkidle")

        page.pdf(
            path=output_path,
            format="A4",
            margin={"top": "15mm", "bottom": "15mm", "left": "14mm", "right": "14mm"},
            print_background=True,
        )
        browser.close()

    print(f"  [reporter] PDF saved successfully: {output_path}")
