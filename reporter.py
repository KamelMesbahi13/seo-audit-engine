def _pair_finding_with_solution(finding: dict, available_fixes: list) -> dict:
    """Matches a finding with its corresponding fix or generates an accurate fallback solution."""
    issue_lower = finding.get("issue", "").lower()
    cat_lower = finding.get("category", "").lower()

    # 1. Exact match first
    for fix in available_fixes:
        fix_issue_lower = fix.get("issue", "").lower()
        if fix_issue_lower == issue_lower:
            return fix

    # 2. Specific keyword direct matching
    SPECIFIC_KEYWORDS = [
        "orphan", "anchor", "broken", "nofollow", "redirect", "sitemap",
        "robots.txt", "schema", "json-ld", "h1", "title", "meta description",
        "ttfb", "cls", "lcp", "render-blocking", "dimensions", "lazy",
        "crawler", "searchgpt", "perplexity", "llms.txt", "freshness", "thin",
        "security", "https", "canonical"
    ]
    for kw in SPECIFIC_KEYWORDS:
        if kw in issue_lower or kw in cat_lower:
            for fix in available_fixes:
                if kw in fix.get("issue", "").lower():
                    return fix

    # 3. Substring match
    for fix in available_fixes:
        fix_issue_lower = fix.get("issue", "").lower()
        if fix_issue_lower in issue_lower or issue_lower in fix_issue_lower:
            return fix

    # 4. Significant non-generic word overlap (exclude common stop words)
    STOP_WORDS = {"links", "link", "page", "pages", "site", "found", "using", "with", "from", "causes", "other", "than"}
    issue_words = [w for w in re.findall(r'\b\w{4,}\b', issue_lower) if w not in STOP_WORDS]
    best_fix = None
    max_overlap = 0
    for fix in available_fixes:
        fix_words = set(re.findall(r'\b\w{4,}\b', fix.get("issue", "").lower()))
        overlap = len(fix_words.intersection(issue_words))
        if overlap > max_overlap:
            max_overlap = overlap
            best_fix = fix

    if best_fix and max_overlap > 0:
        return best_fix

    # 5. Comprehensive fallback solution generation if no explicit fix was returned
    return {
        "issue": finding.get("issue", "Remediation Action"),
        "fix": _generate_fallback_solution(finding),
    }


