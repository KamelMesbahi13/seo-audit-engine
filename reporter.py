def score_color(score: int) -> str:
    """Returns Red for poor/failing scores, Green for strong/good scores, Black for neutral."""
    if score >= 85:
        return COLOR_GREEN
    elif score >= 70:
        return COLOR_BLACK
    return COLOR_RED


def score_grade(score: int) -> str:
    if score >= 90: return "A"
    if score >= 80: return "B"
    if score >= 70: return "C"
    if score >= 60: return "D"
    return "F"


