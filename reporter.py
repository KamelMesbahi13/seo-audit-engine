def _format_code_blocks(text: str) -> str:
    """Format code snippets with clean monospace styling without background fills."""
    lines = text.split("<br>")
    formatted = []
    in_code = False

    for line in lines:
        stripped = line.strip()
        is_code = (
            stripped.startswith("&lt;") or
            stripped.startswith("User-agent:") or
            stripped.startswith("Allow:") or
            stripped.startswith("Disallow:") or
            stripped.startswith("Sitemap:") or
            stripped.startswith("RewriteEngine") or
            stripped.startswith("RewriteCond") or
            stripped.startswith("RewriteRule") or
            stripped.startswith('"@context"') or
            stripped.startswith('"@type"') or
            stripped.startswith("&quot;@context") or
            stripped.startswith("&quot;@type") or
            stripped.startswith("Strict-Transport-Security:") or
            stripped.startswith("X-Content-Type-Options:") or
            stripped.startswith("X-Frame-Options:")
        )

        if is_code and not in_code:
            formatted.append('<div class="code-container">')
            in_code = True
        elif not is_code and in_code:
            formatted.append('</div>')
            in_code = False

        formatted.append(line)

    if in_code:
        formatted.append('</div>')

    return "<br>".join(formatted)


def _e(text) -> str:
    if text is None:
        return ""
    return html.escape(str(text))


