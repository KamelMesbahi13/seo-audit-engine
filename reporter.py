def _clean_detail_text(text: str) -> str:
    """Cleans up raw diagnostic text: replaces giant base64 data URIs, unquotes URLs, and formats breaks."""
    if not text:
        return ""

    # Replace huge base64 image strings
    text = re.sub(
        r'data:image/[a-zA-Z0-9\+\.-]+;base64,[a-zA-Z0-9+/=]{20,}',
        '[inline base64 image data]',
        text
    )

    lines = text.split("\n")
    cleaned_lines = []
    for line in lines:
        stripped = line.strip()
        # Clean social intent share URLs with giant parameter query strings
        if "twitter.com/intent/tweet" in stripped or "facebook.com/sharer" in stripped or "linkedin.com/shareArticle" in stripped:
            stripped = re.sub(r'(\?|\&)(url|text|u)=.*', ' [social share widget link]', stripped)

        # Unquote any encoded non-ASCII/Arabic characters
        try:
            stripped = unquote(stripped)
        except Exception:
            pass

        # Truncate extremely long single-token URLs
        if len(stripped) > 90 and " " not in stripped and ("http://" in stripped or "https://" in stripped):
            cleaned_lines.append(stripped[:85] + "...")
        else:
            cleaned_lines.append(stripped)

    escaped = html.escape("\n".join(cleaned_lines))
    return escaped.replace("\n", "<br>")


