def _filter_items_by_category(items: list, category_key: str) -> list:
    """Filter paired problem-solution items strictly by audit discipline."""
    cat_key = category_key.lower().strip()
    matched = []

    for item in items:
        an = item.get("analyzer", "").lower()
        f = item.get("finding", {})
        issue = f.get("issue", "").lower()
        cat = f.get("category", "").lower()

        if cat_key == "technical":
            if an in ("technical", "robots & sitemaps") or "technical" in an or "robots" in an or "sitemap" in an or cat in ("technical", "security", "infrastructure"):
                matched.append(item)
            elif an == "cross-page patterns" and not any(w in issue for w in ("title", "description", "orphan")):
                matched.append(item)
        elif cat_key == "onpage":
            if an in ("on_page", "onpage") or "on_page" in an or cat in ("on-page", "onpage", "meta", "headings"):
                matched.append(item)
            elif an == "cross-page patterns" and any(w in issue for w in ("title", "description")):
                matched.append(item)
        elif cat_key == "geo":
            if an in ("ai_search_geo", "geo") or "geo" in an or "ai" in an or cat in ("geo", "ai search", "generative seo"):
                matched.append(item)
        elif cat_key == "content":
            if an in ("content_quality", "content") or "content" in an or cat in ("content", "e-e-a-t", "eeat"):
                matched.append(item)
        elif cat_key == "schema":
            if an in ("schema", "schema_analyzer") or "schema" in an or cat in ("schema", "structured data"):
                matched.append(item)
        elif cat_key == "performance":
            if an in ("performance",) or "performance" in an or cat in ("performance", "speed"):
                matched.append(item)
        elif cat_key == "links":
            if an in ("links",) or "link" in an or cat in ("links", "internal links"):
                matched.append(item)
            elif an == "cross-page patterns" and "orphan" in issue:
                matched.append(item)
        elif cat_key == "images":
            if an in ("images",) or "image" in an or cat in ("images", "media"):
                matched.append(item)

    return matched


