    def _calculate_scores(self) -> tuple:
        counts = {"critical": 0, "high": 0, "medium": 0, "low": 0, "passed": 0}
        score = 100

        for f in self.findings:
            sev = f["severity"]
            if sev in counts:
                counts[sev] += 1
            if sev == "critical":
                score -= 25
            elif sev == "high":
                score -= 15
            elif sev == "medium":
                score -= 8
            elif sev == "low":
                score -= 3

        score = max(5, min(100, score))
        if score >= 90:
            grade = "A (Excellent)"
        elif score >= 80:
            grade = "B (Good)"
        elif score >= 70:
            grade = "C+ (Needs Immediate Attention)"
        elif score >= 60:
            grade = "D (High Risk)"
        else:
            grade = "F (Critical Vulnerabilities Detected)"

        return score, grade, counts

