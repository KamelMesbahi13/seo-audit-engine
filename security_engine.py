class SecurityAuditRunner:
    def __init__(self, target_url: str, log_callback=None):
        raw_url = target_url.strip()
        if not raw_url.startswith("http://") and not raw_url.startswith("https://"):
            raw_url = "https://" + raw_url
        self.target_url = raw_url
        self.parsed = urlparse(self.target_url)
        self.domain = self.parsed.netloc.split(":")[0]
        self.scheme = self.parsed.scheme
        self.log_callback = log_callback or (lambda msg: None)
        self.findings = []
        self.logs = []

    def log(self, message: str):
        self.logs.append(message)
        self.log_callback(message)

    def add_finding(self, finding_id: str, severity: str, title: str, location: str,
                    impact: str, recommendation: str, status: str = "failed", details: str = ""):
        self.findings.append({
            "id": finding_id,
            "severity": severity.lower(),  # critical, high, medium, low, passed
            "title": title,
            "location": location,
            "impact": impact,
            "recommendation": recommendation,
            "status": status,
            "details": details
        })

